"""The FileStorage port and its local-disk adapter (contract C10 ``FileStorage``; AC1.10.1).

Keys are generated by the MediaStore (``<owner uuid>/<file uuid>.<ext>``) and validated
here, so a key can never escape the storage root. The local root is a private directory:
nothing serves it as static files (AC1.10.2).
"""

from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path
from typing import Protocol

_KEY = re.compile(r"[0-9a-f-]{36}/[0-9a-f-]{36}\.(jpg|png|pdf)")


class StorageError(RuntimeError):
    """The storage backend failed (disk full, permissions ...)."""


class FileNotStoredError(StorageError):
    """No file is stored under the key."""


class FileStorage(Protocol):
    """Write, read and delete bytes by key."""

    def write(self, key: str, data: bytes) -> None:
        """Store ``data`` under ``key`` (replacing nothing: keys are unique)."""
        ...

    def read(self, key: str) -> bytes:
        """Return the bytes stored under ``key``."""
        ...

    def delete(self, key: str) -> None:
        """Delete ``key``; deleting a missing key is not an error."""
        ...


def check_key(key: str) -> str:
    """Refuse any key that is not a MediaStore-generated key.

    Raises:
        ValueError: For any other shape (for example ``../x``).
    """
    if not _KEY.fullmatch(key):
        raise ValueError("invalid storage key")
    return key


class LocalDiskStorage:
    """Files under a private root directory (development and single-host deployments).

    Writes go to a temporary file in the same directory and are renamed into place, so a
    reader never sees half a file.
    """

    def __init__(self, root: Path) -> None:
        self.root = root

    def _path(self, key: str) -> Path:
        return self.root / check_key(key)

    def write(self, key: str, data: bytes) -> None:
        """Atomically write ``data`` to ``root/key``.

        Raises:
            StorageError: When the file cannot be written.
        """
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            handle, temp_name = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
            try:
                with os.fdopen(handle, "wb") as temp:
                    temp.write(data)
                os.replace(temp_name, path)
            except BaseException:
                Path(temp_name).unlink(missing_ok=True)
                raise
        except OSError as exc:
            raise StorageError(f"could not store a file: {type(exc).__name__}") from exc

    def read(self, key: str) -> bytes:
        """Read ``root/key``.

        Raises:
            FileNotStoredError: When nothing is stored under the key.
            StorageError: When the file exists but cannot be read.
        """
        path = self._path(key)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise FileNotStoredError("no file is stored under this key") from exc
        except OSError as exc:
            raise StorageError(f"could not read a file: {type(exc).__name__}") from exc

    def delete(self, key: str) -> None:
        """Delete ``root/key`` if present.

        Raises:
            StorageError: When the file exists but cannot be deleted.
        """
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as exc:
            raise StorageError(f"could not delete a file: {type(exc).__name__}") from exc
